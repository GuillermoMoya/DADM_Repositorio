package co.edu.unal.reto4_tictactoe.online;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.atomic.AtomicLong;
import java.util.function.LongSupplier;
import java.util.function.Supplier;

import co.edu.unal.reto4_tictactoe.MoveGate;
import co.edu.unal.reto4_tictactoe.TicTacToeGame;

/**
 * In-memory {@link MatchRepository} test double that models the same atomic behavior as the real
 * {@code FirebaseMatchRepository} without any network or Firebase types (design "Testing Strategy"
 * and "Components and Interfaces" §2).
 *
 * <p>This is the <strong>test seam</strong> the property tests (Properties 1–5) and the Lobby/match
 * smoke tests run against. It therefore lives in {@code src/test} rather than production sources:
 * it is only exercised from tests, and keeping it out of {@code src/main} avoids shipping test
 * scaffolding in the app.
 *
 * <h2>Storage model</h2>
 * <ul>
 *   <li>{@code matches}: {@code matchId → MatchState}, the authoritative documents (mirrors
 *       {@code /matches/<id>}).</li>
 *   <li>{@code lobby}: {@code matchId → MatchSummary}, the lightweight index of joinable
 *       {@code WAITING} matches (mirrors {@code /lobby/<id>}); entries are removed as soon as a
 *       match is no longer joinable (join, finish, abandon, host leave).</li>
 *   <li>{@code openMatchesListeners}: live Lobby observers; each receives the full
 *       {@code List<MatchSummary>} on registration and again whenever the lobby changes.</li>
 *   <li>{@code matchListeners}: {@code matchId → observers}; each receives the current
 *       {@link MatchState} on registration and again on every authoritative change.</li>
 * </ul>
 *
 * <h2>Atomicity</h2>
 * All reads and mutations happen while holding this instance's monitor ({@code synchronized}),
 * which models an RTDB transaction's read-decide-write atomicity: given two concurrent
 * {@code joinMatch} calls on the same {@code WAITING} match, exactly one claims the guest slot and
 * the other sees it already taken (Property 2); given two concurrent {@code submitMove} calls, the
 * second sees the updated board/turn and is rejected (Property 1). Listener callbacks are collected
 * while holding the lock and fired after releasing it, so a listener that re-enters the repository
 * does not deadlock.
 *
 * <h2>Shared move/join logic (single source of truth)</h2>
 * The move guard is <b>not</b> implemented here: {@link #submitMove} delegates to the shared,
 * pure {@link OnlineMoveEngine#evaluate(MatchState, String, int)} (task 5.1), the same helper that
 * {@code FirebaseMatchRepository} (task 8.2) calls inside its RTDB transaction, so both validate
 * moves identically. The engine requires {@code status == PLAYING}, the requester to be a
 * participant whose mark equals {@code turn}, and the target cell to be free (reusing
 * {@link MoveGate} for cell/game-over gating); it then applies the move, recomputes {@code winner}
 * with {@link TicTacToeGame#checkForWinner()} and transitions to {@code FINISHED} (or alternates
 * {@code turn}). This repository only mirrors the engine's result onto its stored document and
 * stamps {@code updatedAt}. Likewise, the join claim (task 6.1) is <b>not</b> implemented here:
 * {@link #joinMatch} delegates to the shared, pure {@link OnlineJoinEngine#evaluate(MatchState,
 * String)}, the same helper that {@code FirebaseMatchRepository} (task 8.2) calls inside its RTDB
 * transaction, so both claim the Invitado slot identically (free {@code WAITING} slot → set
 * {@code guestUid}, {@code PLAYING}, {@code turn="X"}); the repository then stamps
 * {@code updatedAt}, records presence and removes the lobby entry.
 *
 * <h2>Determinism</h2>
 * The acting {@code uid} and the clock are injectable so tests are deterministic:
 * {@link #setCurrentUid(String)} controls who the "current player" is for {@code createMatch},
 * {@code joinMatch}, {@code submitMove}, {@code leaveMatch} and {@code registerPresence}, and the
 * clock supplier controls {@code createdAt}/{@code updatedAt}. Match ids are generated by a
 * monotonic counter unless a custom id supplier is provided.
 *
 * <p>Maps requirements: 6.1, 10.1, 14.1, 14.2, 15.1 (plus the join/move invariants shared with the
 * Firebase implementation).
 */
public class FakeMatchRepository implements MatchRepository {

    /** The {@code matchId → MatchState} store (authoritative documents). */
    private final Map<String, MatchState> matches = new HashMap<>();

    /** The {@code matchId → MatchSummary} lobby index of joinable WAITING matches. */
    private final Map<String, MatchSummary> lobby = new LinkedHashMap<>();

    /** Live Lobby observers. */
    private final List<Listener<List<MatchSummary>>> openMatchesListeners = new ArrayList<>();

    /** {@code matchId → observers} of a single match's authoritative state. */
    private final Map<String, List<Listener<MatchState>>> matchListeners = new HashMap<>();

    /** Supplies the acting player's uid for the current call. */
    private volatile Supplier<String> uidSupplier;

    /** Supplies the current epoch-ms timestamp (injectable for deterministic tests). */
    private final LongSupplier clock;

    /** Supplies new match ids. */
    private final Supplier<String> matchIdSupplier;

    /** Monotonic counter backing the default match-id supplier. */
    private final AtomicLong idCounter = new AtomicLong(0);

    /**
     * Creates a repository with a default monotonic clock and sequential match ids
     * ({@code m-0}, {@code m-1}, ...). The current uid starts unset; call
     * {@link #setCurrentUid(String)} before operations that need an acting player.
     */
    public FakeMatchRepository() {
        this(() -> null, new AtomicLong(1_000L)::getAndIncrement, null);
    }

    /**
     * Creates a repository with explicit, injectable dependencies for deterministic tests.
     *
     * @param uidSupplier     supplies the acting player's uid; must be non-{@code null}
     * @param clock           supplies the current epoch-ms timestamp; must be non-{@code null}
     * @param matchIdSupplier supplies new match ids; if {@code null}, sequential ids are used
     */
    public FakeMatchRepository(Supplier<String> uidSupplier, LongSupplier clock,
                               Supplier<String> matchIdSupplier) {
        if (uidSupplier == null) {
            throw new IllegalArgumentException("uidSupplier must be non-null");
        }
        if (clock == null) {
            throw new IllegalArgumentException("clock must be non-null");
        }
        this.uidSupplier = uidSupplier;
        this.clock = clock;
        this.matchIdSupplier =
                (matchIdSupplier != null) ? matchIdSupplier : () -> "m-" + idCounter.getAndIncrement();
    }

    // --- Deterministic-test controls -------------------------------------------------------

    /** Sets the acting player's uid used by the next operations (deterministic tests). */
    public void setCurrentUid(String uid) {
        final String fixed = uid;
        this.uidSupplier = () -> fixed;
    }

    /** @return the acting player's uid, or {@code null} if unset. */
    public String currentUid() {
        return uidSupplier.get();
    }

    /**
     * Direct, non-callback read of a match's authoritative state, for test assertions.
     *
     * @param matchId the match id
     * @return a snapshot copy of the {@link MatchState}, or {@code null} if the match is unknown
     */
    public synchronized MatchState snapshot(String matchId) {
        MatchState s = matches.get(matchId);
        return (s == null) ? null : copyOf(s);
    }

    /** @return the number of matches currently listed as joinable in the Lobby. */
    public synchronized int lobbySize() {
        return lobby.size();
    }

    // --- Lobby ----------------------------------------------------------------------------

    @Override
    public ListenerHandle observeOpenMatches(Listener<List<MatchSummary>> listener) {
        if (listener == null) {
            throw new IllegalArgumentException("listener must be non-null");
        }
        List<MatchSummary> initial;
        synchronized (this) {
            openMatchesListeners.add(listener);
            initial = snapshotLobby();
        }
        // Deliver the initial list outside the lock.
        listener.onChanged(initial);
        return () -> {
            synchronized (FakeMatchRepository.this) {
                openMatchesListeners.remove(listener);
            }
        };
    }

    // --- Creation / join ------------------------------------------------------------------

    @Override
    public void createMatch(ResultCallback<String> onMatchId) {
        if (onMatchId == null) {
            throw new IllegalArgumentException("onMatchId must be non-null");
        }
        String matchId;
        List<Runnable> notifications = new ArrayList<>();
        try {
            synchronized (this) {
                String host = requireUid();
                long now = clock.getAsLong();
                matchId = matchIdSupplier.get();

                MatchState state = new MatchState();
                state.setMatchId(matchId);
                state.setHostUid(host);
                state.setGuestUid(null);
                state.setBoard(MatchState.EMPTY_BOARD);
                state.setTurn(MatchState.MARK_X);
                state.setLifecycle(GameLifecycle.WAITING);
                state.setWinner(MatchState.WINNER_NONE);
                state.setCreatedAt(now);
                state.setUpdatedAt(now);
                Map<String, Boolean> presence = new HashMap<>();
                presence.put(host, true);
                state.setPresence(presence);
                matches.put(matchId, state);

                MatchSummary summary = new MatchSummary();
                summary.setMatchId(matchId);
                summary.setHostUid(host);
                summary.setCreatedAt(now);
                lobby.put(matchId, summary);

                collectMatchNotification(notifications, matchId);
                collectLobbyNotification(notifications);
            }
        } catch (RuntimeException ex) {
            onMatchId.onError(ex);
            return;
        }
        fire(notifications);
        onMatchId.onSuccess(matchId);
    }

    @Override
    public void joinMatch(String matchId, JoinCallback callback) {
        if (callback == null) {
            throw new IllegalArgumentException("callback must be non-null");
        }
        boolean joined;
        List<Runnable> notifications = new ArrayList<>();
        try {
            synchronized (this) {
                MatchState state = matches.get(matchId);
                String requester = requireUid();

                // Transaction: delegate the claim decision to the single shared engine (task 6.1)
                // so the fake and FirebaseMatchRepository (task 8.2) claim the slot identically.
                // The engine computes the claimed state (guestUid, PLAYING, turn=X); the repository
                // owns the side effects (clock, presence, lobby removal, listener notification).
                OnlineJoinEngine.Result result = OnlineJoinEngine.evaluate(state, requester);
                joined = result.isJoined();
                if (joined) {
                    MatchState next = result.getNewState();
                    state.setGuestUid(next.getGuestUid());
                    state.setStatus(next.getStatus());
                    state.setTurn(next.getTurn());
                    state.setUpdatedAt(clock.getAsLong());
                    if (state.getPresence() == null) {
                        state.setPresence(new HashMap<>());
                    }
                    state.getPresence().put(requester, true);
                    lobby.remove(matchId); // No longer joinable.

                    collectMatchNotification(notifications, matchId);
                    collectLobbyNotification(notifications);
                }
            }
        } catch (RuntimeException ex) {
            callback.onError(ex);
            return;
        }
        fire(notifications);
        if (joined) {
            callback.onJoined();
        } else {
            callback.onUnavailable();
        }
    }

    // --- Match in progress ----------------------------------------------------------------

    @Override
    public ListenerHandle observeMatch(String matchId, Listener<MatchState> listener) {
        if (listener == null) {
            throw new IllegalArgumentException("listener must be non-null");
        }
        MatchState initial;
        synchronized (this) {
            matchListeners.computeIfAbsent(matchId, k -> new ArrayList<>()).add(listener);
            MatchState current = matches.get(matchId);
            initial = (current == null) ? null : copyOf(current);
        }
        if (initial != null) {
            listener.onChanged(initial);
        }
        return () -> {
            synchronized (FakeMatchRepository.this) {
                List<Listener<MatchState>> list = matchListeners.get(matchId);
                if (list != null) {
                    list.remove(listener);
                    if (list.isEmpty()) {
                        matchListeners.remove(matchId);
                    }
                }
            }
        };
    }

    @Override
    public void submitMove(String matchId, int cell, MoveCallback callback) {
        if (callback == null) {
            throw new IllegalArgumentException("callback must be non-null");
        }
        boolean applied;
        List<Runnable> notifications = new ArrayList<>();
        try {
            synchronized (this) {
                MatchState state = matches.get(matchId);
                String requester = requireUid();
                // Delegate the legality check and state computation to the single shared engine
                // (task 5.1) so the fake and FirebaseMatchRepository validate moves identically.
                OnlineMoveEngine.Result result = OnlineMoveEngine.evaluate(state, requester, cell);
                applied = result.isApplied();
                if (applied) {
                    // Mirror the engine's fresh state onto the stored document and stamp the clock
                    // (the engine is clock-agnostic; the repository owns timestamps).
                    MatchState next = result.getNewState();
                    state.setBoard(next.getBoard());
                    state.setTurn(next.getTurn());
                    state.setStatus(next.getStatus());
                    state.setWinner(next.getWinner());
                    state.setUpdatedAt(clock.getAsLong());
                    collectMatchNotification(notifications, matchId);
                }
            }
        } catch (RuntimeException ex) {
            callback.onError(ex);
            return;
        }
        fire(notifications);
        if (applied) {
            callback.onApplied();
        } else {
            callback.onRejected();
        }
    }

    // --- Leaving / lifecycle --------------------------------------------------------------

    @Override
    public void leaveMatch(String matchId) {
        List<Runnable> notifications = new ArrayList<>();
        synchronized (this) {
            MatchState state = matches.get(matchId);
            if (state == null) {
                return;
            }
            String requester = requireUid();
            GameLifecycle lifecycle = state.lifecycle();
            if (lifecycle == GameLifecycle.PLAYING) {
                // Explicit, voluntary exit of an active game → ABANDONED.
                state.setLifecycle(GameLifecycle.ABANDONED);
                state.setUpdatedAt(clock.getAsLong());
                lobby.remove(matchId);
                collectMatchNotification(notifications, matchId);
                collectLobbyNotification(notifications);
            } else if (lifecycle == GameLifecycle.WAITING
                    && requester != null && requester.equals(state.getHostUid())) {
                // Orphaned WAITING owned by the host → remove entirely.
                matches.remove(matchId);
                lobby.remove(matchId);
                collectMatchNotification(notifications, matchId);
                collectLobbyNotification(notifications);
            }
            // FINISHED/ABANDONED (or a non-host leaving WAITING): nothing to change.
        }
        fire(notifications);
    }

    @Override
    public void registerPresence(String matchId) {
        List<Runnable> notifications = new ArrayList<>();
        synchronized (this) {
            MatchState state = matches.get(matchId);
            if (state == null) {
                return;
            }
            String requester = requireUid();
            if (state.getPresence() == null) {
                state.setPresence(new HashMap<>());
            }
            state.getPresence().put(requester, true);
            collectMatchNotification(notifications, matchId);
        }
        fire(notifications);
    }

    /**
     * Simulates a transient disconnect of a player: reflects absence without destroying an active
     * {@code PLAYING} match, and cleans up an orphaned {@code WAITING} match owned by that player
     * (models {@code onDisconnect}; design "Lifecycle"/task 8.3 baseline). This is a test helper on
     * the fake, not part of the {@link MatchRepository} contract.
     *
     * @param matchId the match id
     * @param uid     the player that disconnected
     */
    public void simulateDisconnect(String matchId, String uid) {
        List<Runnable> notifications = new ArrayList<>();
        synchronized (this) {
            MatchState state = matches.get(matchId);
            if (state == null) {
                return;
            }
            GameLifecycle lifecycle = state.lifecycle();
            if (lifecycle == GameLifecycle.WAITING
                    && uid != null && uid.equals(state.getHostUid())
                    && state.getGuestUid() == null) {
                // Orphaned WAITING with only the host: safe to remove.
                matches.remove(matchId);
                lobby.remove(matchId);
                collectMatchNotification(notifications, matchId);
                collectLobbyNotification(notifications);
            } else {
                // PLAYING (or anything else): only reflect absence; do NOT abandon.
                if (state.getPresence() == null) {
                    state.setPresence(new HashMap<>());
                }
                state.getPresence().put(uid, false);
                state.setUpdatedAt(clock.getAsLong());
                collectMatchNotification(notifications, matchId);
            }
        }
        fire(notifications);
    }

    // --- Internals ------------------------------------------------------------------------

    private String requireUid() {
        String uid = uidSupplier.get();
        if (uid == null) {
            throw new IllegalStateException("no current uid set; call setCurrentUid(...) first");
        }
        return uid;
    }

    /** Builds the ordered Lobby snapshot (by createdAt, then matchId) under the lock. */
    private List<MatchSummary> snapshotLobby() {
        List<MatchSummary> list = new ArrayList<>();
        for (MatchSummary s : lobby.values()) {
            list.add(copyOf(s));
        }
        list.sort(Comparator.comparingLong(MatchSummary::getCreatedAt)
                .thenComparing(MatchSummary::getMatchId));
        return list;
    }

    /** Queues notifications to every match listener with a fresh snapshot (or null if removed). */
    private void collectMatchNotification(List<Runnable> out, String matchId) {
        List<Listener<MatchState>> list = matchListeners.get(matchId);
        if (list == null || list.isEmpty()) {
            return;
        }
        MatchState current = matches.get(matchId);
        List<Listener<MatchState>> copy = new ArrayList<>(list);
        for (Listener<MatchState> l : copy) {
            MatchState snap = (current == null) ? null : copyOf(current);
            out.add(() -> {
                if (snap != null) {
                    l.onChanged(snap);
                }
            });
        }
    }

    /** Queues notifications to every Lobby listener with a fresh ordered snapshot. */
    private void collectLobbyNotification(List<Runnable> out) {
        if (openMatchesListeners.isEmpty()) {
            return;
        }
        List<Listener<List<MatchSummary>>> copy = new ArrayList<>(openMatchesListeners);
        for (Listener<List<MatchSummary>> l : copy) {
            List<MatchSummary> snap = snapshotLobby();
            out.add(() -> l.onChanged(snap));
        }
    }

    /** Fires queued listener notifications outside the lock to avoid re-entrancy deadlocks. */
    private static void fire(List<Runnable> notifications) {
        for (Runnable r : notifications) {
            r.run();
        }
    }

    private static MatchState copyOf(MatchState s) {
        MatchState c = new MatchState();
        c.setMatchId(s.getMatchId());
        c.setHostUid(s.getHostUid());
        c.setGuestUid(s.getGuestUid());
        c.setBoard(s.getBoard());
        c.setTurn(s.getTurn());
        c.setStatus(s.getStatus());
        c.setWinner(s.getWinner());
        c.setCreatedAt(s.getCreatedAt());
        c.setUpdatedAt(s.getUpdatedAt());
        c.setPresence(s.getPresence() == null ? new HashMap<>() : new HashMap<>(s.getPresence()));
        return c;
    }

    private static MatchSummary copyOf(MatchSummary s) {
        MatchSummary c = new MatchSummary();
        c.setMatchId(s.getMatchId());
        c.setHostUid(s.getHostUid());
        c.setCreatedAt(s.getCreatedAt());
        return c;
    }
}
